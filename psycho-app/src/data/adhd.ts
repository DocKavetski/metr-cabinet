function scoreDiva5(a: number[]): string {
  const sum = (from: number, to: number) =>
    a.slice(from, to).reduce((s, v) => s + (v ? 1 : 0), 0)

  const childIA = sum(0, 9)
  const childHI = sum(9, 18)
  const adultIA = sum(18, 27)
  const adultHI = sum(27, 36)
  const impair = sum(36, 41)

  // DIVA / DSM-5 ориентиры: детство ≥6; взрослость ≥5; нарушения ≥2 сферы
  const childPos = childIA >= 6 || childHI >= 6
  const adultPos = adultIA >= 5 || adultHI >= 5
  const impairPos = impair >= 2

  let verdict = 'по чеклисту критерии СДВГ не набираются'
  if (childPos && adultPos && impairPos) {
    verdict =
      'ориентир DIVA-5: симптомы в детстве и во взрослости + нарушения в ≥2 сферах — показана полная клиническая оценка (не диагноз)'
  } else if (childPos && adultPos) {
    verdict =
      'симптомы в детстве и во взрослости есть, но мало сфер нарушения — уточните влияние на жизнь'
  } else if (adultPos && !childPos) {
    verdict =
      'взрослые симптомы без достаточного детского порога — дифференциальный диагноз / уточнение анамнеза'
  } else if (childPos && !adultPos) {
    verdict = 'детский порог есть, взрослый не набран — актуальная картина слабее'
  }

  return (
    `DIVA-5 (чеклист): детство невним. ${childIA}/9, гип/имп ${childHI}/9; ` +
    `взрослость невним. ${adultIA}/9, гип/имп ${adultHI}/9; нарушения ${impair}/5. ${verdict}.`
  )
}

function labeled(prefix: string, items: string[]): string[] {
  return items.map((t, i) => `${prefix} ${i + 1}. ${t}`)
}

