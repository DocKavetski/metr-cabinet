/** CTQ-28 (Bernstein): клинические шкалы + минимизация */
function scoreCtq(a: number[]): string {
  const raw = (i: number) => a[i] ?? 1
  const rev = (i: number) => 6 - raw(i)

  const emotionalAbuse = [2, 7, 13, 17, 24].reduce((s, i) => s + raw(i), 0)
  const physicalAbuse = [8, 10, 11, 14, 16].reduce((s, i) => s + raw(i), 0)
  const sexualAbuse = [19, 20, 22, 23, 26].reduce((s, i) => s + raw(i), 0)
  const emotionalNeglect = [4, 6, 12, 18, 27].reduce((s, i) => s + rev(i), 0)
  const physicalNeglect = [0, 3, 5].reduce((s, i) => s + raw(i), 0) + rev(1) + rev(25)
  const clinical = emotionalAbuse + physicalAbuse + sexualAbuse + emotionalNeglect + physicalNeglect
  const minimization = [9, 15, 21].reduce((s, i) => s + raw(i), 0)

  const cut = (name: string, v: number, low: number, mod: number, sev: number) => {
    let lvl = 'низкий'
    if (v >= sev) lvl = 'тяжёлый'
    else if (v >= mod) lvl = 'умеренный'
    else if (v >= low) lvl = 'лёгкий'
    return `${name} ${v} (${lvl})`
  }

  const parts = [
    cut('ЭА', emotionalAbuse, 9, 13, 16),
    cut('ФА', physicalAbuse, 8, 10, 13),
    cut('СА', sexualAbuse, 6, 8, 13),
    cut('ЭН', emotionalNeglect, 10, 15, 18),
    cut('ФН', physicalNeglect, 8, 10, 13),
  ]

  return `CTQ: клиническая сумма ${clinical}/125. ${parts.join('; ')}. Минимизация/идеализация: ${minimization}/15. ЭА/ФА/СА — насилие; ЭН/ФН — запущенность.`
}

