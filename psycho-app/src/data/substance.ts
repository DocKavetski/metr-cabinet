/** AUDIT: пункты 1–8 → 0–4; 9–10 → 0/2/4 */
function scoreAudit(a: number[]): string {
  if (a.length < 10) return 'Нет данных'
  let total = 0
  for (let i = 0; i < 8; i++) total += a[i] ?? 0
  // 9–10: на бланке часто 0 / 2 / 4; если ввели 1 или 3 — трактуем как ближайшие стандартные
  for (let i = 8; i < 10; i++) {
    const v = a[i] ?? 0
    if (v === 0) total += 0
    else if (v === 1 || v === 2) total += 2
    else total += 4
  }
  let level = 'низкий риск'
  if (total >= 20) level = 'возможна зависимость — нужна клиническая оценка'
  else if (total >= 16) level = 'вредное употребление'
  else if (total >= 8) level = 'опасное / рискованное употребление'
  return `AUDIT: ${total}/40 — ${level}.`
}

