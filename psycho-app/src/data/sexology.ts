function scoreCsbi13(a: number[]): string {
  const total = a.reduce((sum, v) => sum + v, 0)
  const label =
    total >= 35
      ? '≥35 — высокий риск синдрома компульсивного сексуального поведения; нужна клиническая оценка CSBD'
      : total >= 30
        ? '30–34 — повышенный уровень (скрининговый порог); уточните клинически'
        : 'ниже скрининговых порогов'
  return `CSBI-13: ${total}/65 — ${label}.`
}

