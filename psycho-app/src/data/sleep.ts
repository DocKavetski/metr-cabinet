/** Сумма двух пунктов 0–6 → компонент PSQI 0–3 */
function psqiPairToComponent(sum: number): number {
  if (sum <= 0) return 0
  if (sum <= 2) return 1
  if (sum <= 4) return 2
  return 3
}

/** Сумма нарушений сна 0–30 → компонент 0–3 */
function psqiDisturbanceComponent(sum: number): number {
  if (sum <= 0) return 0
  if (sum <= 9) return 1
  if (sum <= 18) return 2
  return 3
}

function scorePsqi(a: number[]): string {
  const c1 = a[0] ?? 0
  const c2 = psqiPairToComponent((a[1] ?? 0) + (a[2] ?? 0))
  const c3 = a[3] ?? 0
  const c4 = a[4] ?? 0
  const disturbSum = a.slice(5, 14).reduce((s, v) => s + (v ?? 0), 0)
  const c5 = psqiDisturbanceComponent(disturbSum)
  const c6 = a[14] ?? 0
  const c7 = psqiPairToComponent((a[15] ?? 0) + (a[16] ?? 0))
  const components = [c1, c2, c3, c4, c5, c6, c7]
  const total = components.reduce((s, v) => s + v, 0)
  const names = [
    'качество',
    'латентность',
    'длительность',
    'эффективность',
    'нарушения',
    'медикаменты',
    'дневная функция',
  ]
  const detail = names.map((n, i) => `${n} ${components[i]}`).join('; ')
  const flag =
    total > 5
      ? 'глобальный балл >5 — нарушенное качество сна (скрининг)'
      : 'глобальный балл ≤5 — качество сна в пределах типичного порога'
  return `PSQI: ${total}/21 (${detail}) — ${flag}.`
}

