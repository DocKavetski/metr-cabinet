function lsasQuestions(): string[] {
  const out: string[] = []
  lsasSituations.forEach((s, i) => {
    out.push(`${i + 1}. Страх — ${s}`)
    out.push(`${i + 1}. Избегание — ${s}`)
  })
  return out
}

function scoreLsas(a: number[]): string {
  let fear = 0
  let avoid = 0
  for (let i = 0; i < 24; i++) {
    fear += a[i * 2] ?? 0
    avoid += a[i * 2 + 1] ?? 0
  }
  const total = fear + avoid
  let label = 'ниже типичного скринингового порога'
  if (total >= 90) label = 'тяжёлая социальная тревога (по сумме)'
  else if (total >= 60) label = 'выраженная социальная тревога'
  else if (total >= 30) label = 'возможна социальная тревога — клиническая оценка'
  return `LSAS: ${total}/144 (страх ${fear}/72, избегание ${avoid}/72) — ${label}.`
}

