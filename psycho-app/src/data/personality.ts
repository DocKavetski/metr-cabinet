/** PID-5-BF: домены (0-based индексы пунктов) */
function scorePid5bf(a: number[]): string {
  const domains: [string, number[]][] = [
    ['Негативный аффект', [7, 8, 9, 10, 14]],
    ['Отстранённость', [3, 12, 13, 15, 17]],
    ['Антагонизм', [16, 18, 19, 21, 24]],
    ['Растормаживание', [0, 1, 2, 4, 5]],
    ['Психотизм', [6, 11, 20, 22, 23]],
  ]
  const parts = domains.map(([name, idxs]) => {
    const mean = idxs.reduce((s, i) => s + (a[i] ?? 0), 0) / idxs.length
    const flag = mean >= 1.5 ? '↑' : ''
    return `${name} ${mean.toFixed(2)}${flag}`
  })
  const totalMean = a.reduce((s, v) => s + v, 0) / a.length
  return `PID-5-BF: общий средний ${totalMean.toFixed(2)}/3. Домены: ${parts.join('; ')}. (↑ при среднем домена ≥1,5 — ориентир настороженности.)`
}

