/** Разбор: «26» или домены «5 3 6 3 2 5 6» / «5+3+6+…» */
function parseCognitiveScore(value: string, maxTotal: number): number | null {
  const raw = value.trim().replace(/,/g, '.')
  if (!raw) return null

  if (/^\d+(\.\d+)?$/.test(raw)) {
    const n = Number(raw)
    if (!Number.isFinite(n) || n < 0 || n > maxTotal) return null
    return Math.round(n)
  }

  const parts = raw
    .split(/[+;\s|/]+/)
    .map((p) => p.trim())
    .filter(Boolean)
    .map((p) => Number(p))

  if (parts.length < 2 || parts.some((n) => !Number.isFinite(n) || n < 0)) return null
  const sum = parts.reduce((a, b) => a + b, 0)
  if (sum < 0 || sum > maxTotal) return null
  return Math.round(sum)
}

