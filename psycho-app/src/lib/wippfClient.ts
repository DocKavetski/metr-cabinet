function youTextFor(scale: WippfScaleScore): string {
  const pack = YOU[scale.id]
  if (!pack) {
    return scale.level === 'high'
      ? `По шкале «${scale.name}» вы ближе к полюсу «${scale.highLabel}».`
      : scale.level === 'low'
        ? `По шкале «${scale.name}» вы ближе к полюсу «${scale.lowLabel}».`
        : `По шкале «${scale.name}» вы в зоне баланса — между «${scale.lowLabel}» и «${scale.highLabel}».`
  }
  if (scale.level === 'high') return pack.high
  if (scale.level === 'low') return pack.low
  return pack.mid
}

function overallFor(report: WippfReport): string {
  if (report.extremes.length === 0) {
    return (
      'Ваш профиль сейчас довольно ровный: мало крайностей. Это хороший фон, чтобы замечать нюансы — ' +
      'не «что со мной не так», а где вам чуть теснее или чуть важнее обычного.'
    )
  }
  const names = report.extremes
    .slice(0, 5)
    .map((s) => `«${s.name}» (${s.lowLabel} ↔ ${s.highLabel}, ${s.score}/12)`)
    .join(', ')
  if (report.high.length && !report.low.length) {
    return (
      `Некоторые качества для вас особенно яркие. Имеет смысл присмотреться: ${names}. ` +
      'Это не «слишком много характера» — скорее то, на что вы опираетесь и чем можете уставать.'
    )
  }
  if (report.low.length && !report.high.length) {
    return (
      `Где-то качества звучат тише обычного. Стоит мягко посмотреть: ${names}. ` +
      'Тихий полюс — не недостаток, а подсказка, чего сейчас меньше в вашей жизни.'
    )
  }
  return (
    `В профиле есть контраст — и яркие, и тихие полюса. Особенно заметны: ${names}. ` +
    'Именно такие расхождения часто и бывают содержанием споров с близкими или с самим собой.'
  )
}

function reflectionsFor(report: WippfReport): string[] {
  const items: string[] = []
  const conflictTop = [...report.conflict].sort((a, b) => b.score - a.score)[0]
  if (conflictTop) {
    items.push(
      `Когда становится трудно, куда вы уходите чаще — в тело, в дела, к людям или в мысли? ` +
        `Сейчас заметнее «${conflictTop.name}» (${conflictTop.lowLabel} ↔ ${conflictTop.highLabel}).`,
    )
  }
  const focus = report.extremes.slice(0, 3)
  for (const s of focus) {
    items.push(
      `Где в ближайшую неделю проявляется «${s.name}»: ближе к «${s.lowLabel}» или к «${s.highLabel}»? Что это даёт вам — и чего стоит.`,
    )
  }
  items.push(
    'Если рядом есть близкий человек, сравните ваши шкалы не чтобы спорить, кто прав, а чтобы увидеть разные ценности.',
  )
  items.push(
    'Выберите одно качество, которое сейчас больше всего живёт в отношениях или на работе, и понаблюдайте за ним три дня — без оценки «хорошо/плохо».',
  )
  return items.slice(0, 6)
}

export function buildWippfClientReport(report: WippfReport): WippfClientReport {
  return {
    lead:
      'Это не диагноз и не оценка характера. Опросник показывает, какие качества для вас сейчас ' +
      'особенно важны — и куда вы обычно «уходите», когда становится трудно. ' +
      'Его можно перечитать дома и принести вопросы на встречу.',
    howToRead:
      'Каждая шкала — от 3 до 12. Зелёная полоса 6–9 — условная норма, «достаточно». ' +
      'Левее (3–5) — ближе к левому слову, правее (10–12) — к правому. ' +
      'Ни один полюс не хороший и не плохой: «грязнуля» и «чистюля» — просто разные способы жить.',
    overall: overallFor(report),
    reflections: reflectionsFor(report),
    scales: report.scales.map((s) => ({
      id: s.id,
      name: s.name,
      group: s.group,
      score: s.score,
      level: s.level,
      flag: s.flag,
      lowLabel: s.lowLabel,
      highLabel: s.highLabel,
      youText: youTextFor(s),
    })),
  }
}
